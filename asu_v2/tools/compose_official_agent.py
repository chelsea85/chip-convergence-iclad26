def snippet_defs() -> str:
    parts = []
    for helper_name, builder_name, gen in (
            ("_VIA_BAR_SAFE_HELPER", "via_bar_safe_snippet",
             v2_repairs.via_bar_safe_pass),
            ("_TRACK_SHIFT_HELPER", "track_shift_snippet",
             v2_repairs.track_shift_pass),
            ("_V1_PATCH_HELPER", "v1_patch_snippet", v2_repairs.v1_patch_pass)):
        helper = getattr(v2_repairs, helper_name)
        body = gen()
        # everything the generator appends after the helper, as a literal
        tail = body[len(helper):]
        parts.append(f"{helper_name} = {helper!r}\n\n"
                     f"_{builder_name.upper()}_TAIL = {tail!r}\n\n"
                     f"def {builder_name}() -> str:\n"
                     f'    """Byte-identical to v2_repairs.{gen.__name__}()."""\n'
                     f"    return {helper_name} + _{builder_name.upper()}_TAIL\n")
    return "\n".join(parts)


def compose() -> str:
    return V2_HEADER + snippet_defs() + BODY


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check-against", default=None,
                    help="runs dir with <Block>/<stack>/cand.py to byte-verify")
    a = ap.parse_args()
    text = compose()
    out = V2 / "official_submission" / "agent.py"
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} ({len(text):,} chars)")

    # self-check: builders in the composed file == the dev generators
    ns = {}
    exec(compile(text.replace('if __name__ == "__main__":\n    sys.exit(main())',
                              ''), "agent_v2", "exec"), ns)
    assert ns["via_bar_safe_snippet"]() == v2_repairs.via_bar_safe_pass()
    assert ns["track_shift_snippet"]() == v2_repairs.track_shift_pass()
    assert ns["v1_patch_snippet"]() == v2_repairs.v1_patch_pass()
    print("builder equality: OK")

    if a.check_against:
        runs = Path(a.check_against)
        tc = (ROOT / "ICLAD-Hackathon-2026" / "problem-categories"
              / "ICLAD26-ASU-Problems" / "testcase" / "asap7" / "block"
              / "layout_script")
        ok = True
        for blk in BLOCKS:
            emitted, _ = ns["repair"]((tc / f"{blk}.py").read_text())
            cand = (runs / blk / STACK_NAME / "cand.py").read_text()
            match = emitted == cand
            ok &= match
            print(f"{blk}: byte-identical to measured candidate: {match}")
        if not ok:
            print("MISMATCH — do not ship")
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
