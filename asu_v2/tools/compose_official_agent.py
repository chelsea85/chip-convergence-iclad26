        try:
            up = Path(usage_path)
            up.parent.mkdir(parents=True, exist_ok=True)
            up.write_text(json.dumps({"input_tokens": 0, "output_tokens": 0,
                                      "calls": 0}, indent=1))
        except OSError as e:
            _log(f"usage write skipped (read-only, expected under official runner): "
                 f"{type(e).__name__}")
